#Requires -Version 5.1
<#
.SYNOPSIS
  Prompt for opt-in pool membership and write inference-shards.active.env.

.DESCRIPTION
  Always-on shards come from inference-shards.core.env (inference) or
  pool72-shards.core.env (Pool72 / -ShardProfile Pool72). inference optional hosts
  (gaming-a/gaming-c/gaming-b/secondary/pool-opt-in) come from inference-shards.gaming.env. Pool72/Pool80 optional
  hosts (gaming-c/gaming-a/gaming-b/secondary/pool-opt-in) come from their gaming catalogs when the
  operator opts in at cluster start.

  Official llama.cpp RPC fixes backends at coordinator start (no hot join/leave):
  https://github.com/ggml-org/llama.cpp/blob/master/tools/rpc/README.md

.NOTES
  Dot-source from Invoke-AlfaAiCluster.ps1. ASCII-only for Windows PowerShell 5.1.
#>

function Get-AlfainferenceGamingSelectionPath {
    param([Parameter(Mandatory)][string]$LlcDir)
    return (Join-Path $LlcDir 'inference-gaming-selection.env')
}

function Get-AlfainferenceActiveShardsPath {
    param([Parameter(Mandatory)][string]$LlcDir)
    return (Join-Path $LlcDir 'inference-shards.active.env')
}

function Read-AlfainferenceGamingSelection {
    param([Parameter(Mandatory)][string]$SelectionPath)
    $sel = @{
        Include59  = $false
        Include219 = $false
        Include249 = $false
        Include248 = $false
        Include100 = $false
    }
    if (-not (Test-Path -LiteralPath $SelectionPath)) {
        return $sel
    }
    foreach ($line in Get-Content -LiteralPath $SelectionPath) {
        $trim = ($line -replace '#.*$', '').Trim()
        if (-not $trim) { continue }
        if ($trim -match '^INCLUDE_59=(1|true|yes)$') { $sel.Include59 = $true }
        if ($trim -match '^INCLUDE_219=(1|true|yes)$') { $sel.Include219 = $true }
        if ($trim -match '^INCLUDE_249=(1|true|yes)$') { $sel.Include249 = $true }
        if ($trim -match '^INCLUDE_248=(1|true|yes)$') { $sel.Include248 = $true }
        if ($trim -match '^INCLUDE_100=(1|true|yes)$') { $sel.Include100 = $true }
        if ($trim -match '^INCLUDE_59=(0|false|no)$') { $sel.Include59 = $false }
        if ($trim -match '^INCLUDE_219=(0|false|no)$') { $sel.Include219 = $false }
        if ($trim -match '^INCLUDE_249=(0|false|no)$') { $sel.Include249 = $false }
        if ($trim -match '^INCLUDE_248=(0|false|no)$') { $sel.Include248 = $false }
        if ($trim -match '^INCLUDE_100=(0|false|no)$') { $sel.Include100 = $false }
    }
    return $sel
}

function Write-AlfainferenceGamingSelection {
    param(
        [Parameter(Mandatory)][string]$SelectionPath,
        [Parameter(Mandatory)][bool]$Include59,
        [Parameter(Mandatory)][bool]$Include219,
        [Parameter(Mandatory)][bool]$Include249,
        [Parameter(Mandatory)][bool]$Include248,
        [Parameter(Mandatory)][bool]$Include100
    )
    $dir = Split-Path -Parent $SelectionPath
    if (-not (Test-Path -LiteralPath $dir)) {
        New-Item -ItemType Directory -Path $dir -Force | Out-Null
    }
    $body = @(
        '# Local last answers for inference opt-in (gitignored).'
        '# Regenerated by Start-Stop-AlfaAi.ps1 / Resolve-AlfainferenceActiveShards.'
        ("INCLUDE_59={0}" -f $(if ($Include59) { '1' } else { '0' }))
        ("INCLUDE_219={0}" -f $(if ($Include219) { '1' } else { '0' }))
        ("INCLUDE_249={0}" -f $(if ($Include249) { '1' } else { '0' }))
        ("INCLUDE_248={0}" -f $(if ($Include248) { '1' } else { '0' }))
        ("INCLUDE_100={0}" -f $(if ($Include100) { '1' } else { '0' }))
    ) -join "`n"
    Set-Content -LiteralPath $SelectionPath -Value $body -Encoding ASCII
}

function Read-AlfaYesNoDefault {
    param(
        [Parameter(Mandatory)][string]$Prompt,
        [Parameter(Mandatory)][bool]$DefaultYes
    )
    $hint = if ($DefaultYes) { 'Y/n' } else { 'y/N' }
    $raw = Read-Host ("{0} [{1}]" -f $Prompt, $hint)
    if ([string]::IsNullOrWhiteSpace($raw)) {
        return $DefaultYes
    }
    $t = $raw.Trim().ToLowerInvariant()
    if ($t -eq 'y' -or $t -eq 'yes' -or $t -eq '1') { return $true }
    if ($t -eq 'n' -or $t -eq 'no' -or $t -eq '0') { return $false }
    Write-Host ("Unrecognized '{0}' -- using default ({1})." -f $raw, $(if ($DefaultYes) { 'Y' } else { 'N' })) -ForegroundColor Yellow
    return $DefaultYes
}

function Get-AlfainferenceGamingCatalogLines {
    param([Parameter(Mandatory)][string]$GamingCatalogPath)
    $rows = @()
    if (-not (Test-Path -LiteralPath $GamingCatalogPath)) {
        throw "Missing gaming catalog: $GamingCatalogPath"
    }
    foreach ($line in Get-Content -LiteralPath $GamingCatalogPath) {
        $trim = ($line -replace '#.*$', '').Trim()
        if (-not $trim) { continue }
        $parts = $trim -split '\s+'
        if ($parts.Count -lt 3) { continue }
        $label = if ($parts.Count -ge 4) { $parts[3] } else { $parts[0] }
        # Optional MODEL_PCT sits in field 5 when LABEL is present (HOST PORT VRAM LABEL [PCT]).
        $pct = if ($parts.Count -ge 5) { $parts[4] } else { '' }
        $shardLine = if ($pct) {
            ("{0} {1} {2} {3}" -f $parts[0], $parts[1], $parts[2], $pct)
        } else {
            ("{0} {1} {2}" -f $parts[0], $parts[1], $parts[2])
        }
        $rows += [pscustomobject]@{
            Host      = $parts[0]
            Port      = [int]$parts[1]
            Vram      = $parts[2]
            Label     = $label
            ShardLine = $shardLine
        }
    }
    return $rows
}

function Build-AlfainferenceActiveShardsContent {
    param(
        [Parameter(Mandatory)][string]$CorePath,
        [Parameter(Mandatory)][string]$GamingCatalogPath,
        [Parameter(Mandatory)][bool]$Include59,
        [Parameter(Mandatory)][bool]$Include219,
        [Parameter(Mandatory)][bool]$Include249,
        [Parameter(Mandatory)][bool]$Include248,
        [Parameter(Mandatory)][bool]$Include100
    )
    if (-not (Test-Path -LiteralPath $CorePath)) {
        throw "Missing core shard list: $CorePath"
    }
    $coreLines = @()
    foreach ($line in Get-Content -LiteralPath $CorePath) {
        $trim = ($line -replace '#.*$', '').Trim()
        if ($trim) { $coreLines += $trim }
    }
    $wantHosts = @{}
    if ($Include219) { $wantHosts['orchestrator'] = $true }
    if ($Include59) { $wantHosts['orchestrator'] = $true }
    if ($Include249) { $wantHosts['orchestrator'] = $true }
    if ($Include248) { $wantHosts['orchestrator'] = $true }
    if ($Include100) { $wantHosts['orchestrator'] = $true }

    # Gaming hosts after inference pair, before orchestrator. secondary then pool-opt-in after orchestrator (legacy core order).
    $before93 = @()
    $from93 = @()
    $seen93 = $false
    foreach ($cl in $coreLines) {
        $parts = $cl -split '\s+'
        if (-not $seen93 -and $parts[0] -eq 'orchestrator') {
            $seen93 = $true
        }
        if ($seen93) { $from93 += $cl } else { $before93 += $cl }
    }

    $gamingInsert = @()
    $opt248Line = $null
    $opt100Line = $null
    foreach ($row in (Get-AlfainferenceGamingCatalogLines -GamingCatalogPath $GamingCatalogPath)) {
        if (-not $wantHosts.ContainsKey($row.Host)) { continue }
        if ($row.Host -eq 'orchestrator') {
            $opt248Line = $row.ShardLine
            continue
        }
        if ($row.Host -eq 'orchestrator') {
            $opt100Line = $row.ShardLine
            continue
        }
        $gamingInsert += $row.ShardLine
    }

    $out = New-Object System.Collections.Generic.List[string]
    $out.Add('# Generated by Resolve-AlfainferenceActiveShards.ps1 (gitignored).') | Out-Null
    $out.Add('# Do not commit. Coordinator + verify must use this file for this start.') | Out-Null
    $out.Add('# Official RPC backends are fixed at llama-server start:') | Out-Null
    $out.Add('# https://github.com/ggml-org/llama.cpp/blob/master/tools/rpc/README.md') | Out-Null
    foreach ($l in $before93) { $out.Add($l) | Out-Null }
    foreach ($l in $gamingInsert) { $out.Add($l) | Out-Null }
    $insertedAfter93 = $false
    foreach ($l in $from93) {
        $out.Add($l) | Out-Null
        $parts = $l -split '\s+'
        if (-not $insertedAfter93 -and $parts[0] -eq 'orchestrator') {
            if ($opt248Line) { $out.Add($opt248Line) | Out-Null }
            if ($opt100Line) { $out.Add($opt100Line) | Out-Null }
            $insertedAfter93 = $true
        }
    }
    if (-not $insertedAfter93) {
        if ($opt248Line) { $out.Add($opt248Line) | Out-Null }
        if ($opt100Line) { $out.Add($opt100Line) | Out-Null }
    }
    return ($out -join "`n")
}

function Resolve-AlfainferenceActiveShards {
    param(
        [Parameter(Mandatory)][string]$LlcDir,
        [ValidateSet('Ask', 'Flags', 'Last', 'None')]
        [string]$Mode = 'Ask',
        [ValidateSet('inference', 'Pool72', 'Pool80')]
        [string]$ShardProfile = 'inference',
        [bool]$Include59 = $false,
        [bool]$Include219 = $false,
        [bool]$Include249 = $false,
        [bool]$Include248 = $false,
        [bool]$Include100 = $false
    )

    # Pool72/Pool80 use dense budgets (pool*-shards.*.env). inference keeps hybrid-27B lists.
    # Same active path (inference-shards.active.env) so coordinator deploy stays one file.
    if ($ShardProfile -eq 'Pool72') {
        $corePath = Join-Path $LlcDir 'pool72-shards.core.env'
        $gamingPath = Join-Path $LlcDir 'pool72-shards.gaming.env'
    } elseif ($ShardProfile -eq 'Pool80') {
        $corePath = Join-Path $LlcDir 'pool80-shards.core.env'
        $gamingPath = Join-Path $LlcDir 'pool80-shards.gaming.env'
    } else {
        $corePath = Join-Path $LlcDir 'inference-shards.core.env'
        $gamingPath = Join-Path $LlcDir 'inference-shards.gaming.env'
    }
    $selectionPath = Get-AlfainferenceGamingSelectionPath -LlcDir $LlcDir
    $activePath = Get-AlfainferenceActiveShardsPath -LlcDir $LlcDir
    $last = Read-AlfainferenceGamingSelection -SelectionPath $selectionPath

    switch ($Mode) {
        'None' {
            $Include59 = $false
            $Include219 = $false
            $Include249 = $false
            $Include248 = $false
            $Include100 = $false
        }
        'Last' {
            $Include59 = [bool]$last.Include59
            $Include219 = [bool]$last.Include219
            $Include249 = [bool]$last.Include249
            $Include248 = [bool]$last.Include248
            $Include100 = [bool]$last.Include100
        }
        'Flags' {
            # caller-supplied Include* already set
        }
        'Ask' {
            Write-Host ''
            if ($ShardProfile -eq 'Pool72') {
                Write-Host 'Pool72 opt-in hosts (THIS start only; dense 72B Q5 needs full mesh)' -ForegroundColor Cyan
                Write-Host 'Always-on: inference / orchestrator / hub. Core alone cannot fit 72B weights -- opt-in all gaming hosts when possible.' -ForegroundColor Gray
            } elseif ($ShardProfile -eq 'Pool80') {
                Write-Host 'Pool80 opt-in hosts (THIS start only; Coder-Next Q5 needs full mesh)' -ForegroundColor Cyan
                Write-Host 'Always-on: inference / orchestrator / hub. Core alone cannot fit 80B Q5 weights -- opt-in all gaming hosts when possible.' -ForegroundColor Gray
            } else {
                Write-Host 'inference opt-in hosts (THIS start only)' -ForegroundColor Cyan
                Write-Host 'Always-on: inference / orchestrator / hub. Opt-in join needs a full stop+start.' -ForegroundColor Gray
            }
            Write-Host 'Leaving an opted-in host while the pool is green requires stop then start without it.' -ForegroundColor Gray
            Write-Host ''
            if ($ShardProfile -eq 'inference') {
                Write-Host 'inference opt-in: gaming-a/gaming-c/gaming-b/secondary/pool-opt-in (never required for core green).' -ForegroundColor Gray
                Write-Host 'gaming-c/gaming-b blocked while 14B train lock is set (train-desktop-menu.ps1).' -ForegroundColor Gray
                Write-Host ''
                $Include219 = Read-AlfaYesNoDefault -Prompt 'Include gaming-a gaming-worker-a (RTX 5060 :31352)?' -DefaultYes:([bool]$last.Include219)
                $Include59 = Read-AlfaYesNoDefault -Prompt 'Include gaming-c gaming-worker-c (RTX 5070 :31351)?' -DefaultYes:([bool]$last.Include59)
                $Include249 = Read-AlfaYesNoDefault -Prompt 'Include gaming-b gaming-worker-b (RTX 5070 :31358)?' -DefaultYes:([bool]$last.Include249)
                $Include248 = Read-AlfaYesNoDefault -Prompt 'Include secondary gpu-248 (GTX 1070 :31355)?' -DefaultYes:([bool]$last.Include248)
                $Include100 = Read-AlfaYesNoDefault -Prompt 'Include pool-opt-in VM100 (GTX 1660 Super :31354)?' -DefaultYes:([bool]$last.Include100)
            } else {
                $Include219 = Read-AlfaYesNoDefault -Prompt 'Include gaming-a gaming-worker-a (RTX 5060 :31352)?' -DefaultYes:([bool]$last.Include219)
                $Include59 = Read-AlfaYesNoDefault -Prompt 'Include gaming-c gaming-worker-c (RTX 5070 :31351)?' -DefaultYes:([bool]$last.Include59)
                $Include249 = Read-AlfaYesNoDefault -Prompt 'Include gaming-b gaming-worker-b (RTX 5070 :31358)?' -DefaultYes:([bool]$last.Include249)
                $Include248 = Read-AlfaYesNoDefault -Prompt 'Include secondary gpu-248 (GTX 1070 :31355)?' -DefaultYes:([bool]$last.Include248)
                $Include100 = Read-AlfaYesNoDefault -Prompt 'Include pool-opt-in VM100 (GTX 1660 Super :31354)?' -DefaultYes:([bool]$last.Include100)
            }
        }
    }

    if ($Include59 -or $Include249 -or $Include219 -or $Include248 -or $Include100) {
        Write-Host ''
        Write-Host 'NOTE: Opted-in hosts deploy automatically from orchestrator when Y (SSH).' -ForegroundColor Yellow
        Write-Host 'Ensure OpenSSH + Docker + the host image are ready on each opted-in host.' -ForegroundColor Yellow
    }

    if ($ShardProfile -eq 'Pool72' -or $ShardProfile -eq 'Pool80') {
        $optCount = 0
        if ($Include219) { $optCount++ }
        if ($Include59) { $optCount++ }
        if ($Include249) { $optCount++ }
        if ($Include248) { $optCount++ }
        if ($Include100) { $optCount++ }
        if ($optCount -lt 5) {
            Write-Host ''
            if ($ShardProfile -eq 'Pool80') {
                Write-Host ('WARNING: Pool80 core-only TENSOR_SPLIT is ~29.5 GB; 80B Q5 weights are ~57 GB. Opt-in count={0}/5.' -f $optCount) -ForegroundColor Yellow
            } else {
                Write-Host ('WARNING: Pool72 core-only TENSOR_SPLIT is ~29.5 GB; 72B Q5 weights are ~52 GB. Opt-in count={0}/5.' -f $optCount) -ForegroundColor Yellow
            }
            Write-Host 'Prefer Include all of gaming-a/gaming-c/gaming-b/secondary/pool-opt-in for a full-mesh start.' -ForegroundColor Yellow
        }
    }

    Write-AlfainferenceGamingSelection -SelectionPath $selectionPath `
        -Include59:$Include59 -Include219:$Include219 -Include249:$Include249 `
        -Include248:$Include248 -Include100:$Include100

    $content = Build-AlfainferenceActiveShardsContent -CorePath $corePath `
        -GamingCatalogPath $gamingPath `
        -Include59:$Include59 -Include219:$Include219 -Include249:$Include249 `
        -Include248:$Include248 -Include100:$Include100
    Set-Content -LiteralPath $activePath -Value $content -Encoding ASCII

    $summary = @(($ShardProfile + '-core'))
    if ($Include219) { $summary += 'gaming-a' }
    if ($Include59) { $summary += 'gaming-c' }
    if ($Include249) { $summary += 'gaming-b' }
    if ($Include248) { $summary += 'secondary' }
    if ($Include100) { $summary += 'pool-opt-in' }

    return [pscustomobject]@{
        ActivePath    = $activePath
        SelectionPath = $selectionPath
        ShardProfile  = $ShardProfile
        Include59     = $Include59
        Include219    = $Include219
        Include249    = $Include249
        Include248    = $Include248
        Include100    = $Include100
        Summary       = ($summary -join '+')
    }
}
