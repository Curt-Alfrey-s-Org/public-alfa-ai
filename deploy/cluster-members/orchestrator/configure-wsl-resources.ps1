#Requires -Version 5.1
<#
.SYNOPSIS
    Cap WSL2 RAM on orchestrator and document 4096 MiB VRAM preflight for Win11 desktop.

.DESCRIPTION
    WSL defaults to ~50% of host RAM when uncapped (starves Win11 on this 31 GB box).
    GeForce WDDM has no driver knob to permanently reserve VRAM; inference enforces a
    desktop margin via inference-shards.env (tensor 10 GB on the 12 GB 3060) and
    preflight-gpu-empty.sh MAX_MIB=4096 at shard deploy.

.EXAMPLE
    .\configure-wsl-resources.ps1
    .\configure-wsl-resources.ps1 -WslMemoryGB 6
#>
[CmdletBinding()]
param(
    [ValidateRange(4, 16)]
    [int]$WslMemoryGB = 8
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$wslConfig = Join-Path $env:USERPROFILE '.wslconfig'
$required = @(
    'networkingMode=mirrored',
    'swap=0',
    "memory=${WslMemoryGB}GB",
    'dnsTunneling=true',
    'firewall=true',
    'autoProxy=true',
    'vmIdleTimeout=-1',
    'hostAddressLoopback=true',
    'instanceIdleTimeout=-1'
)

function Get-WslConfigText {
    if (-not (Test-Path -LiteralPath $wslConfig)) {
        return ''
    }
    Get-Content -LiteralPath $wslConfig -Raw
}

function Set-WslConfigKey {
    param(
        [Parameter(Mandatory)][string]$Section,
        [Parameter(Mandatory)][string]$Key,
        [Parameter(Mandatory)][string]$Value
    )
    $script:WslText = Get-WslConfigText
    $pattern = "(?ms)\[$([regex]::Escape($Section))\][^\[]*"
    if ($WslText -match $pattern) {
        $block = $Matches[0]
        if ($block -match "(?m)^\s*$([regex]::Escape($Key))\s*=") {
            $newBlock = [regex]::Replace($block, "(?m)^\s*$([regex]::Escape($Key))\s*=.*$", "$Key=$Value")
        }
        else {
            $newBlock = $block.TrimEnd() + "`n$Key=$Value`n"
        }
        $script:WslText = $WslText -replace [regex]::Escape($block), $newBlock
    }
    else {
        $script:WslText += "`n[$Section]`n$Key=$Value`n"
    }
}

$script:WslText = Get-WslConfigText
if (-not $WslText.Trim()) {
    $script:WslText = @"
# ALFa orchestrator WSL2 - generated by configure-wsl-resources.ps1

"@
}

Set-WslConfigKey -Section 'wsl2' -Key 'networkingMode' -Value 'mirrored'
Set-WslConfigKey -Section 'wsl2' -Key 'swap' -Value '0'
Set-WslConfigKey -Section 'wsl2' -Key 'memory' -Value "${WslMemoryGB}GB"
Set-WslConfigKey -Section 'wsl2' -Key 'dnsTunneling' -Value 'true'
Set-WslConfigKey -Section 'wsl2' -Key 'firewall' -Value 'true'
Set-WslConfigKey -Section 'wsl2' -Key 'autoProxy' -Value 'true'
Set-WslConfigKey -Section 'wsl2' -Key 'vmIdleTimeout' -Value '-1'

if ($WslText -notmatch '\[experimental\]') {
    $WslText += "`n[experimental]`n"
}
Set-WslConfigKey -Section 'experimental' -Key 'hostAddressLoopback' -Value 'true'

if ($WslText -notmatch '\[general\]') {
    $WslText += "`n[general]`n"
}
Set-WslConfigKey -Section 'general' -Key 'instanceIdleTimeout' -Value '-1'

Set-Content -LiteralPath $wslConfig -Value $WslText.TrimEnd() -Encoding UTF8
Write-Host "Wrote $wslConfig (memory=${WslMemoryGB}GB)" -ForegroundColor Green

Write-Host ''
Write-Host 'VRAM preflight (4096 MiB MAX_MIB for Win11 desktop on RTX 3060):' -ForegroundColor Cyan
Write-Host '  - inference-shards.env: orchestrator tensor split = 10 GB on the 12 GB card' -ForegroundColor Gray
Write-Host '  - deploy-grev27-pool-shard.ps1: preflight MAX_MIB=4096 before rpc-server start' -ForegroundColor Gray
Write-Host '  - No GeForce driver setting permanently reserves VRAM; close heavy GPU apps before inference load' -ForegroundColor Yellow
Write-Host '  - Optional: disable HW accel in Chrome/Edge (Settings -> System) to save ~0.5-1.5 GB VRAM' -ForegroundColor Gray
Write-Host ''
Write-Host 'After next cluster start, coordinator on hub regenerates TENSOR_SPLIT from inference-shards.env.' -ForegroundColor Cyan
Write-Host 'Apply WSL cap now: wsl --shutdown' -ForegroundColor Yellow