#!/usr/bin/env bash
# Build deploy/llamacpp-rpc/.env.rpc from inference-shards.env (declarative shard list).
#
# Usage (coordinator host hub CPU):
#   bash deploy/cluster-members/hub/write-grev27-pool-env.sh
#
# Env overrides:
#   inference_SHARDS_FILE   path to shard list (default: deploy/llamacpp-rpc/inference-shards.env)
#   MODELS_DIR           GGUF directory on coordinator host
#   SLOT_CACHE_DIR       slot cache path
#   MAIN_PORT            coordinator port (default 31360)
#   CTX_SIZE             default 262144 (52428 tokens/slot at PARALLEL=5; Qwen3.8
#                        native max -- https://huggingface.co/Qwen/Qwen3.8-27B.
#                        llama-server: --ctx-size is total KV among slots --
#                        https://github.com/ggml-org/llama.cpp/blob/master/tools/server/README.md
#                        Do not set 327680 without YaRN (Pool72 path).
#   PARALLEL             default 5 (2 user + 3 automated Q8; OOM rollback 5->4)
#   BATCH_SIZE           default 8192 (llama-server --batch-size; logical prefill)
#   UBATCH_SIZE          default 1024 (llama-server --ubatch-size; physical micro-batch)
#   LOAD_TIMEOUT         default 900
#   inference_SHARDS_FILE   override shard list (e.g. inference-shards.no-1660s.env for A/B)
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_DIR="${ALFA_REPO_DIR:-$(cd "$SCRIPT_DIR/../../.." && pwd)}"
LLC="$REPO_DIR/deploy/llamacpp-rpc"
SHARDS_FILE="${inference_SHARDS_FILE:-$LLC/inference-shards.env}"
ENV_RPC="$LLC/.env.rpc"

MODELS_DIR="${MODELS_DIR:-/mnt/hub/alfa-ai/llama-cpp/models}"
MODEL_FILE="${inference_MODEL_FILE:-Qwen3.8-27B-Q8_0.gguf}"
MODEL_ALIAS="${MODEL_ALIAS:-qwen3.6-27b}"
SLOT_CACHE_DIR="${SLOT_CACHE_DIR:-$(bash "$SCRIPT_DIR/default-slot-cache-dir-111.sh" "$REPO_DIR")}"
MAIN_PORT="${MAIN_PORT:-31360}"
CTX_SIZE="${CTX_SIZE:-262144}"
PARALLEL="${PARALLEL:-5}"
BATCH_SIZE="${BATCH_SIZE:-8192}"
UBATCH_SIZE="${UBATCH_SIZE:-1024}"
LOAD_TIMEOUT="${LOAD_TIMEOUT:-900}"
# b8552: raise fixed httplib pool under LiteLLM load (#20684). Use 16 after hub b8485+ (#20817).
THREADS_HTTP="${THREADS_HTTP:-64}"

if [[ ! -f "$SHARDS_FILE" ]]; then
  echo "ERROR: missing shard list: $SHARDS_FILE" >&2
  exit 1
fi

backends=()
splits=()
while read -r line || [[ -n "$line" ]]; do
  line="${line%%#*}"
  line="$(echo "$line" | sed 's/^[[:space:]]*//;s/[[:space:]]*$//')"
  [[ -z "$line" ]] && continue
  read -r host port vram_gb pct <<<"$line"
  if [[ -z "$host" || -z "$port" || -z "$vram_gb" ]]; then
    echo "ERROR: bad shard line in $SHARDS_FILE: $line" >&2
    exit 1
  fi
  if [[ -n "${pct:-}" ]]; then
    ts="$(awk -v gb="$vram_gb" -v p="$pct" 'BEGIN { printf "%.1f", gb * p / 100 }')"
  else
    ts="$vram_gb"
  fi
  backends+=("${host}:${port}")
  splits+=("$ts")
done <"$SHARDS_FILE"

if [[ "${#backends[@]}" -lt 2 ]]; then
  echo "ERROR: need at least 2 shards in $SHARDS_FILE (found ${#backends[@]})" >&2
  exit 1
fi

if [[ -n "${COORDINATOR_LOOPBACK_LOCAL_SHARD:-}" ]]; then
  local_i=0
  for i in "${!backends[@]}"; do
    if [[ "${backends[$i]}" == "hub" ]]; then
      backends[$i]="$COORDINATOR_LOOPBACK_LOCAL_SHARD"
      local_i=1
      break
    fi
  done
  if [[ "$local_i" -ne 1 ]]; then
    echo "WARN: COORDINATOR_LOOPBACK_LOCAL_SHARD set but no hub in shard list" >&2
  fi
fi

RPC_BACKENDS="$(IFS=,; echo "${backends[*]}")"
TENSOR_SPLIT="$(IFS=,; echo "${splits[*]}")"

mkdir -p "$(dirname "$ENV_RPC")"
cat >"$ENV_RPC" <<EOF
# Generated by write-grev27-pool-env-from-shards.sh from $SHARDS_FILE
# Coordinator: CPU on hub :${MAIN_PORT}. GPU-only shards (--fit off).
MAIN_PORT=$MAIN_PORT
MODELS_DIR=$MODELS_DIR
SLOT_CACHE_DIR=$SLOT_CACHE_DIR
MODEL_FILE=$MODEL_FILE
MODEL_ALIAS=$MODEL_ALIAS
RPC_BACKENDS=$RPC_BACKENDS
TENSOR_SPLIT=$TENSOR_SPLIT
N_GPU_LAYERS=999
CTX_SIZE=$CTX_SIZE
CACHE_TYPE_K=q4_0
CACHE_TYPE_V=q4_0
PARALLEL=$PARALLEL
BATCH_SIZE=$BATCH_SIZE
UBATCH_SIZE=$UBATCH_SIZE
CACHE_REUSE=256
CHAT_TEMPLATE=chatml
THREADS_HTTP=$THREADS_HTTP
LLAMA_API_KEY=change-me
CUDA_VISIBLE_DEVICES=
LOAD_TIMEOUT=$LOAD_TIMEOUT
EOF

echo "Wrote $ENV_RPC"
echo "  SHARDS_FILE=$SHARDS_FILE"
echo "  RPC_BACKENDS=$RPC_BACKENDS"
echo "  TENSOR_SPLIT=$TENSOR_SPLIT (sum=$(echo "$TENSOR_SPLIT" | awk -F, '{s=0; for(i=1;i<=NF;i++) s+=$i; printf "%.1f", s}') GB nominal; order = load priority, fastest first)"
echo "  PARALLEL=$PARALLEL CTX_SIZE=$CTX_SIZE (per-slot=$(( CTX_SIZE / PARALLEL ))) BATCH_SIZE=$BATCH_SIZE UBATCH_SIZE=$UBATCH_SIZE"
lead="$MODELS_DIR/$MODEL_FILE"
if [[ ! -f "$lead" ]]; then
  echo "ERROR: 27B GGUF missing at $lead" >&2
  exit 1
fi
