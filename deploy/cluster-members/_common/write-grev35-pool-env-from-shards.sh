#!/usr/bin/env bash
# Build deploy/llamacpp-rpc/.env.rpc from pool35-shards.env (declarative shard list).
#
# Usage (coordinator host hub CPU):
#   bash deploy/cluster-members/hub/write-grev35-env.sh
#
# Env overrides:
#   POOL35_SHARDS_FILE   path to shard list (default: deploy/llamacpp-rpc/pool35-shards.env)
#   MODELS_DIR           GGUF directory on coordinator host
#   SLOT_CACHE_DIR       slot cache path
#   MAIN_PORT            coordinator port (default 31360)
#   CTX_SIZE             default 4096
#   LOAD_TIMEOUT         default 900
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_DIR="${ALFA_REPO_DIR:-$(cd "$SCRIPT_DIR/../../.." && pwd)}"
LLC="$REPO_DIR/deploy/llamacpp-rpc"
SHARDS_FILE="${POOL35_SHARDS_FILE:-$LLC/pool35-shards.env}"
ENV_RPC="$LLC/.env.rpc"

MODELS_DIR="${MODELS_DIR:-/mnt/hub/alfa-ai/llama-cpp/models}"
MODEL_FILE="${POOL35_MODEL_FILE:-Qwen3.6-35B-A3B-UD-Q4_K_XL.gguf}"
SLOT_CACHE_DIR="${SLOT_CACHE_DIR:-$(bash "$SCRIPT_DIR/default-slot-cache-dir-111.sh" "$REPO_DIR")}"
MAIN_PORT="${MAIN_PORT:-31360}"
CTX_SIZE="${CTX_SIZE:-4096}"
FIT_TARGET="${FIT_TARGET:-2048,1024,512}"
FIT_CTX="${FIT_CTX:-4096}"
LOAD_TIMEOUT="${LOAD_TIMEOUT:-900}"
THREADS_HTTP="${THREADS_HTTP:-64}"

if [[ ! -f "$SHARDS_FILE" ]]; then
  echo "ERROR: missing shard list: $SHARDS_FILE" >&2
  exit 1
fi

backends=()
while read -r line || [[ -n "$line" ]]; do
  line="${line%%#*}"
  line="$(echo "$line" | sed 's/^[[:space:]]*//;s/[[:space:]]*$//')"
  [[ -z "$line" ]] && continue
  read -r host port vram_gb pct <<<"$line"
  if [[ -z "$host" || -z "$port" || -z "$vram_gb" ]]; then
    echo "ERROR: bad shard line in $SHARDS_FILE: $line" >&2
    exit 1
  fi
  backends+=("${host}:${port}")
done <"$SHARDS_FILE"

if [[ "${#backends[@]}" -lt 2 ]]; then
  echo "ERROR: need at least 2 shards in $SHARDS_FILE (found ${#backends[@]})" >&2
  exit 1
fi

if [[ -n "${COORDINATOR_LOOPBACK_LOCAL_SHARD:-}" ]]; then
  local_i=0
  for i in "${!backends[@]}"; do
    if [[ "${backends[$i]}" == "hub" ]]; then
      backends[$i]="$COORDINATOR_LOOPBACK_LOCAL_SHARD"
      local_i=1
      break
    fi
  done
  if [[ "$local_i" -ne 1 ]]; then
    echo "WARN: COORDINATOR_LOOPBACK_LOCAL_SHARD set but no hub in shard list" >&2
  fi
fi

RPC_BACKENDS="$(IFS=,; echo "${backends[*]}")"

mkdir -p "$(dirname "$ENV_RPC")"
cat >"$ENV_RPC" <<EOF
# Generated by write-grev35-pool-env-from-shards.sh from $SHARDS_FILE
# Coordinator: CPU on hub :${MAIN_PORT}. MoE --fit on (no fixed TENSOR_SPLIT).
MAIN_PORT=$MAIN_PORT
MODELS_DIR=$MODELS_DIR
SLOT_CACHE_DIR=$SLOT_CACHE_DIR
MODEL_FILE=$MODEL_FILE
MODEL_ALIAS=qwen3.6-35b-a3b
RPC_BACKENDS=$RPC_BACKENDS
CTX_SIZE=$CTX_SIZE
FIT_TARGET=$FIT_TARGET
FIT_CTX=$FIT_CTX
CACHE_TYPE_K=q8_0
CACHE_TYPE_V=q8_0
PARALLEL=1
CHAT_TEMPLATE=chatml
THREADS_HTTP=$THREADS_HTTP
LLAMA_API_KEY=change-me
CUDA_VISIBLE_DEVICES=
LOAD_TIMEOUT=$LOAD_TIMEOUT
EOF

echo "Wrote $ENV_RPC"
echo "  RPC_BACKENDS=$RPC_BACKENDS"
lead="$MODELS_DIR/$MODEL_FILE"
if [[ ! -f "$lead" ]]; then
  echo "ERROR: 35B GGUF missing at $lead" >&2
  echo "  Run on hub: PROFILE=moe35 bash deploy/llamacpp-rpc/scripts/fetch-qwen3-coder.sh" >&2
  exit 1
fi
